/**
 * `lefine strings types`: writes a `.d.ts` with every key of a Lefine app, so a
 * key added in the dashboard shows up in the editor.
 *
 * The texts are written as string literal types in the source language, in the
 * same `{ namespace: { dotted.key: text } }` tree the CDN serves
 * (`v/{version}/{locale}/translations.json`). use-intl and next-intl read argument types
 * from literal ICU texts themselves (`{count, plural, ...}` -> `count: number`), so
 * the file only has to register the messages with their `AppConfig`; it adds no
 * runtime code. This is what next-intl's own `createMessagesDeclaration` does for
 * local JSON files; here the source is the Lefine project, not a file in the repo.
 */

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { OpClient } from "./client.js";
import { icuArgs } from "./icu-args.js";
import type { AppSummary } from "./types.js";

/** Where the bindings' `useTranslations` (or `useStrings`) takes its types from. */
export type TypesBinding = "next-intl" | "use-intl" | "lefine/strings" | "none";

export interface SourceKey {
  namespace: string;
  key: string;
  /** Source text; empty when it was never written. */
  text: string;
}

export interface StringsTypesInput {
  workspace: string;
  app: Pick<AppSummary, "slug" | "sourceLocale" | "targetLocales">;
  keys: SourceKey[];
  binding: TypesBinding;
}

export interface RenderedTypes {
  text: string;
  keyCount: number;
  /** `namespace:key` pairs left out: a text and a group under the same name (the CDN file cannot hold both either). */
  conflicts: string[];
}

/** Server text inside a `//` line comment: printable ASCII only, so a line break cannot end the comment. */
const oneLine = (text: string) => JSON.stringify(text.replace(/[^\x20-\x7E]/g, "?"));

/** A string as TypeScript source: JSON is valid TS; U+2028/U+2029 are escaped so no tool reads them as a line break. */
const literal = (text: string) => JSON.stringify(text).replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");

type Tree = { [name: string]: Tree | string };

/** The CDN's nesting: "billing.trial.ends" is billing -> trial -> ends. */
function buildTree(keys: SourceKey[]): { tree: Tree; conflicts: string[] } {
  const tree: Tree = Object.create(null);
  const conflicts: string[] = [];
  const sorted = [...keys].sort((a, b) => a.namespace.localeCompare(b.namespace) || a.key.localeCompare(b.key));
  for (const entry of sorted) {
    const ns = (tree[entry.namespace] ??= Object.create(null));
    if (typeof ns === "string") continue;
    const path = entry.key.split(".");
    let node: Tree = ns;
    let ok = true;
    for (let i = 0; i < path.length - 1; i++) {
      const next = (node[path[i]!] ??= Object.create(null));
      if (typeof next === "string") {
        ok = false;
        break;
      }
      node = next;
    }
    const leaf = path[path.length - 1]!;
    if (!ok || (leaf in node && typeof node[leaf] === "object")) {
      conflicts.push(`${entry.namespace}:${entry.key}`);
      continue;
    }
    node[leaf] = entry.text;
  }
  return { tree, conflicts };
}

function renderTree(tree: Tree, pad: string): string[] {
  const lines: string[] = [];
  for (const name of Object.keys(tree)) {
    const value = tree[name]!;
    if (typeof value === "string") {
      // A text nobody wrote yet has no literal to read arguments from.
      lines.push(`${pad}${literal(name)}: ${value === "" ? "string" : literal(value)};`);
    } else {
      lines.push(`${pad}${literal(name)}: {`, ...renderTree(value, `${pad}  `), `${pad}};`);
    }
  }
  return lines;
}

function leaves(tree: Tree, prefix: string, out: string[]): string[] {
  for (const name of Object.keys(tree)) {
    const value = tree[name]!;
    const path = prefix ? `${prefix}.${name}` : name;
    if (typeof value === "string") out.push(path);
    else leaves(value, path, out);
  }
  return out;
}

/** The file `lefine strings types` writes. Pure: same input, same text. */
export function renderStringsTypes(input: StringsTypesInput): RenderedTypes {
  const { tree, conflicts } = buildTree(input.keys);
  const keyPaths = leaves(tree, "", []);
  const locales = [...new Set([input.app.sourceLocale, ...input.app.targetLocales])];
  const parts = [
    `// Generated by \`lefine strings types\` from the Lefine app ${oneLine(`${input.workspace}/${input.app.slug}`)} (source language ${oneLine(input.app.sourceLocale)}).`,
    "// Do not edit: run the command again after keys change in Lefine. Types only, no runtime code.",
    "",
    "/** Every text of the app in its source language, as the CDN serves it: { namespace: { key: text } }. */",
    `export type LefineMessages = ${Object.keys(tree).length === 0 ? "{}" : ["{", ...renderTree(tree, "  "), "}"].join("\n")};`,
    "",
    '/** "namespace.key" for every key. */',
    `export type LefineKey = ${keyPaths.length === 0 ? "never" : keyPaths.map(literal).join("\n  | ")};`,
    "",
    "/** The app's languages, source first. */",
    `export type LefineLocale = ${locales.map(literal).join(" | ")};`,
    "",
  ];
  if (input.binding === "lefine/strings") {
    // ICU arguments per "namespace.key" (read from the source text): a key with arguments needs them.
    const args: string[] = [];
    for (const k of [...input.keys].sort((a, b) => `${a.namespace}.${a.key}`.localeCompare(`${b.namespace}.${b.key}`))) {
      const found = k.text ? icuArgs(k.text) : null;
      if (!found || Object.keys(found).length === 0 || conflicts.includes(`${k.namespace}:${k.key}`)) continue;
      const fields = Object.entries(found).map(([name, type]) => `${literal(name)}: ${type}`).join("; ");
      args.push(`  ${literal(`${k.namespace}.${k.key}`)}: { ${fields} };`);
    }
    parts.push(
      '/** ICU arguments of each key that has any: t("ns.key", { ... }) is checked against these. */',
      `export type LefineArgs = ${args.length === 0 ? "{}" : ["{", ...args, "}"].join("\n")};`,
      "",
      "// createTranslator (lefine/strings), useStrings (lefine/react) and getStrings (lefine/next, lefine/server) now accept",
      "// only these namespaces, keys and arguments. The import puts lefine/strings in the program: an app that imports only",
      "// lefine/next and lefine/react would otherwise skip this block, and every key would pass.",
      'import type {} from "lefine/strings";',
      'declare module "lefine/strings" {',
      "  interface StringsConfig {",
      "    Messages: LefineMessages;",
      "    Args: LefineArgs;",
      "  }",
      "}",
      "",
    );
  } else if (input.binding !== "none") {
    parts.push(
      `// useTranslations / getTranslations from ${input.binding} now know every key and its arguments.`,
      `declare module ${literal(input.binding)} {`,
      "  interface AppConfig {",
      "    Messages: LefineMessages;",
      "  }",
      "}",
      "",
    );
  }
  return { text: parts.join("\n"), keyCount: keyPaths.length, conflicts };
}

/**
 * Which `AppConfig` to extend, from the app's package.json. `@better-i18n/next` and next-intl
 * read it from "next-intl"; `@better-i18n/use-intl` re-exports use-intl's hooks.
 */
export function detectBinding(rootDir: string): TypesBinding {
  const file = join(rootDir, "package.json");
  if (!existsSync(file)) return "none";
  let pkg: Record<string, Record<string, string> | undefined>;
  try {
    pkg = JSON.parse(readFileSync(file, "utf-8"));
  } catch {
    return "none";
  }
  const deps = { ...pkg.dependencies, ...pkg.devDependencies, ...pkg.peerDependencies };
  if ("lefine" in deps) return "lefine/strings";
  if ("next-intl" in deps || "@better-i18n/next" in deps) return "next-intl";
  if ("use-intl" in deps || "@better-i18n/use-intl" in deps) return "use-intl";
  return "none";
}

interface KeyPage {
  items: Array<{ namespace: string; key: string; translations?: Record<string, { text?: string } | undefined> }>;
  nextCursor: string | null;
}

/** At 200 keys a page: a million keys. A server that keeps answering past that is not a list. */
const MAX_PAGES = 5000;

/** Every key of the app with its source text, all pages (`strings.keys.list`). */
export async function fetchSourceKeys(ops: OpClient, appId: string, sourceLocale: string): Promise<SourceKey[]> {
  const keys: SourceKey[] = [];
  const seen = new Set<string>();
  let cursor: string | undefined;
  for (let page = 0; page < MAX_PAGES; page++) {
    const result = await ops.callOp<KeyPage>("strings.keys.list", { appId, locale: sourceLocale, limit: 200, ...(cursor ? { cursor } : {}) });
    for (const item of result?.items ?? []) {
      if (typeof item?.namespace !== "string" || typeof item.key !== "string" || item.key === "") continue;
      const text = item.translations?.[sourceLocale]?.text;
      keys.push({ namespace: item.namespace, key: item.key, text: typeof text === "string" ? text : "" });
    }
    const next = result?.nextCursor;
    if (!next) return keys;
    if (seen.has(next)) throw new Error("The key list repeated a page; stopped so the file is not written from a partial list.");
    seen.add(next);
    cursor = next;
  }
  throw new Error(`The key list did not end after ${MAX_PAGES} pages; stopped so the file is not written from a partial list.`);
}
