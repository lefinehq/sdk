import { afterEach, beforeEach, describe, expect, it } from "bun:test";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import ts from "typescript";
import { defaultTypesFile, stringsTypesCommand } from "../strings-commands.js";
import { detectBinding, renderStringsTypes, type SourceKey, type TypesBinding } from "../strings-types.js";

const APP = { slug: "web", sourceLocale: "en", targetLocales: ["de", "pt-BR"] };
const KEYS: SourceKey[] = [
  { namespace: "common", key: "hello", text: "Hello {name}" },
  { namespace: "common", key: "items", text: "{count, plural, one {# item} other {# items}}" },
  { namespace: "billing", key: "trial.ends", text: "Your trial ends on {date, date, short}" },
  { namespace: "billing", key: "trial.title", text: "Trial" },
  { namespace: "common", key: "unwritten", text: "" },
];

describe("renderStringsTypes", () => {
  it("nests dotted keys like the CDN file and writes texts as literal types", () => {
    const { text, keyCount, conflicts } = renderStringsTypes({ workspace: "acme", app: APP, keys: KEYS, binding: "next-intl" });
    expect(keyCount).toBe(5);
    expect(conflicts).toEqual([]);
    expect(text).toContain('  "billing": {\n    "trial": {\n      "ends": "Your trial ends on {date, date, short}";');
    expect(text).toContain('"hello": "Hello {name}";');
    // Nothing written yet: no literal to read arguments from.
    expect(text).toContain('"unwritten": string;');
    expect(text).toContain('export type LefineKey = "billing.trial.ends"');
    expect(text).toContain('export type LefineLocale = "en" | "de" | "pt-BR";');
    expect(text).toContain('declare module "next-intl" {\n  interface AppConfig {\n    Messages: LefineMessages;');
  });

  it("is the same text for the same keys in any order", () => {
    const a = renderStringsTypes({ workspace: "acme", app: APP, keys: KEYS, binding: "use-intl" }).text;
    const b = renderStringsTypes({ workspace: "acme", app: APP, keys: [...KEYS].reverse(), binding: "use-intl" }).text;
    expect(a).toBe(b);
  });

  it("leaves out a key that is both a text and a group, and says which", () => {
    const { text, conflicts } = renderStringsTypes({
      workspace: "acme",
      app: APP,
      keys: [
        { namespace: "a", key: "x", text: "X" },
        { namespace: "a", key: "x.y", text: "XY" },
      ],
      binding: "none",
    });
    expect(conflicts).toEqual(["a:x.y"]);
    expect(text).toContain('"x": "X";');
    expect(text).not.toContain("declare module");
  });

  it("server text cannot leave its string or comment", () => {
    const hostile = 'a"; } declare const pwned: 1; //\u2028x';
    const { text } = renderStringsTypes({
      workspace: "acme\u2028evil();",
      app: { ...APP, slug: "web" },
      keys: [{ namespace: "n", key: hostile, text: hostile }],
      binding: "none",
    });
    // The header comment is printable ASCII only.
    expect(text.split("\n")[0]).toBe('// Generated by `lefine strings types` from the Lefine app "acme?evil();/web" (source language "en").');
    expect(text).not.toContain("\u2028");
    const diagnostics = ts
      .transpileModule(text, { reportDiagnostics: true, compilerOptions: { target: ts.ScriptTarget.ES2022 } })
      .diagnostics?.map((d) => d.messageText);
    expect(diagnostics).toEqual([]);
    // One property in namespace n: the hostile text stayed a string literal.
    expect(text).toContain(`${JSON.stringify(hostile).replace("\u2028", "\\u2028")}: ${JSON.stringify(hostile).replace("\u2028", "\\u2028")};`);
  });
});

/** Type-checks `use` against the generated file with the real next-intl / use-intl the bindings use. */
function typecheck(binding: Exclude<TypesBinding, "none">, use: string[]): string[] {
  const dir = mkdtempSync(join(tmpdir(), "lefine-strings-types-"));
  try {
    const owner = binding === "next-intl" ? "next" : "use-intl";
    const real = resolve(import.meta.dir, "../../../../", owner, "node_modules", binding);
    mkdirSync(join(dir, "node_modules"));
    symlinkSync(real, join(dir, "node_modules", binding));
    writeFileSync(join(dir, "lefine-strings.d.ts"), renderStringsTypes({ workspace: "acme", app: APP, keys: KEYS, binding }).text);
    writeFileSync(join(dir, "use.ts"), [`import { useTranslations } from "${binding}";`, ...use, "export {};"].join("\n"));
    const program = ts.createProgram([join(dir, "use.ts"), join(dir, "lefine-strings.d.ts")], {
      strict: true,
      noEmit: true,
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      target: ts.ScriptTarget.ES2022,
      jsx: ts.JsxEmit.ReactJSX,
      skipLibCheck: true,
      types: [],
    });
    return ts
      .getPreEmitDiagnostics(program)
      .filter((d) => d.file?.fileName.endsWith("use.ts"))
      .map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n"));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

describe("the generated file with the React and Next bindings", () => {
  for (const binding of ["next-intl", "use-intl"] as const) {
    it(`${binding}: known keys and their arguments compile`, () => {
      expect(
        typecheck(binding, [
          'const t = useTranslations("common");',
          't("hello", { name: "Ada" });',
          't("items", { count: 3 });',
          't("unwritten");',
          'const b = useTranslations("billing");',
          'b("trial.ends", { date: new Date() });',
          'b("trial.title");',
        ]),
      ).toEqual([]);
    }, 60_000);

    it(`${binding}: an unknown key, namespace or a missing argument is a type error`, () => {
      expect(typecheck(binding, ['const t = useTranslations("common");', 't("nope");'])).not.toEqual([]);
      expect(typecheck(binding, ['useTranslations("nope");'])).not.toEqual([]);
      expect(typecheck(binding, ['const t = useTranslations("common");', 't("hello");'])).not.toEqual([]);
      expect(typecheck(binding, ['const t = useTranslations("common");', 't("items", { count: "3" });'])).not.toEqual([]);
    }, 60_000);
  }
});

describe("the generated file with lefine/strings", () => {
  /** Type-checks against the runtime's source (packages/lefine (lefine/strings)), mapped by path. */
  function check(use: string[], header = ['import { createTranslator } from "lefine/strings";']): string[] {
    const dir = mkdtempSync(join(tmpdir(), "lefine-strings-own-"));
    try {
      writeFileSync(join(dir, "lefine-strings.d.ts"), renderStringsTypes({ workspace: "acme", app: APP, keys: KEYS, binding: "lefine/strings" }).text);
      writeFileSync(join(dir, "use.ts"), [...header, "declare const messages: any;", ...use, "export {};"].join("\n"));
      const program = ts.createProgram([join(dir, "use.ts"), join(dir, "lefine-strings.d.ts")], {
        strict: true,
        noEmit: true,
        module: ts.ModuleKind.ESNext,
        moduleResolution: ts.ModuleResolutionKind.Bundler,
        target: ts.ScriptTarget.ES2022,
        lib: ["lib.es2022.d.ts", "lib.dom.d.ts"],
        jsx: ts.JsxEmit.ReactJSX,
        skipLibCheck: true,
        types: [],
        paths: {
          "lefine/strings": [resolve(import.meta.dir, "../../../../lefine/src/strings/index.ts")],
          "lefine/react": [resolve(import.meta.dir, "../../../../lefine/src/react/index.tsx")],
        },
      });
      return ts
        .getPreEmitDiagnostics(program)
        .filter((d) => d.file?.fileName.endsWith("use.ts"))
        .map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n"));
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  }

  it("known namespaces and keys compile; unknown ones are type errors", () => {
    expect(
      check([
        'const t = createTranslator({ locale: "en", messages, namespace: "common" });',
        't("hello", { name: "Ada" }); t("items", { count: 2 }); t("unwritten"); t.has("unwritten");',
        'const b = createTranslator({ locale: "en", messages, namespace: "billing" });',
        'b("trial.ends", { date: new Date() }); b("trial.title");',
        'const all = createTranslator({ locale: "en", messages });',
        'all("billing.trial.title");',
      ]),
    ).toEqual([]);
    expect(check(['createTranslator({ locale: "en", messages, namespace: "common" })("nope");'])).not.toEqual([]);
    expect(check(['createTranslator({ locale: "en", messages, namespace: "nope" });'])).not.toEqual([]);
    expect(check(['createTranslator({ locale: "en", messages })("common.nope");'])).not.toEqual([]);
  }, 60_000);

  // DX walk 2026-10-29: a Next app imports lefine/next and lefine/react, never lefine/strings. The augmentation of
  // "lefine/strings" then did nothing (that module was not in the program) and every key passed.
  it("useStrings from lefine/react is typed in an app that never imports lefine/strings", () => {
    const react = ['import { useStrings } from "lefine/react";'];
    expect(check(['const t = useStrings("common");', 't("hello", { name: "Ada" });'], react)).toEqual([]);
    expect(check(['const t = useStrings("common");', 't("nope");'], react)).not.toEqual([]);
    expect(check(['useStrings("nope");'], react)).not.toEqual([]);
  }, 60_000);

  it("ICU arguments are typed: missing or wrong ones are errors (audit, Do next 7)", () => {
    const t = 'const t = createTranslator({ locale: "en", messages, namespace: "common" });';
    expect(check([t, 't("hello");'])).not.toEqual([]);
    expect(check([t, 't("items", { count: "2" });'])).not.toEqual([]);
    expect(check([t, 't("items", { cnt: 2 });'])).not.toEqual([]);
    expect(check(['createTranslator({ locale: "en", messages })("billing.trial.ends", { date: "soon" });'])).not.toEqual([]);
  }, 60_000);
});

describe("detectBinding", () => {
  let dir: string;
  beforeEach(() => void (dir = mkdtempSync(join(tmpdir(), "lefine-binding-"))));
  afterEach(() => rmSync(dir, { recursive: true, force: true }));
  const pkg = (deps: Record<string, string>) => writeFileSync(join(dir, "package.json"), JSON.stringify({ dependencies: deps }));

  it("reads the app's package.json", () => {
    expect(detectBinding(dir)).toBe("none");
    pkg({ "@better-i18n/next": "^0.10.0", "next-intl": "^4" });
    expect(detectBinding(dir)).toBe("next-intl");
    pkg({ "@better-i18n/use-intl": "^0.11.0" });
    expect(detectBinding(dir)).toBe("use-intl");
    pkg({ lefine: "^0.1.0", "next-intl": "^4" });
    expect(detectBinding(dir)).toBe("lefine/strings");
    writeFileSync(join(dir, "package.json"), "{ not json");
    expect(detectBinding(dir)).toBe("none");
  });
});

describe("lefine strings types", () => {
  const realFetch = globalThis.fetch;
  const realExit = process.exit;
  const realLog = console.log;
  const realErr = console.error;
  let dir: string;
  let logs: string[];
  let pages: Array<{ cursor?: string; locale?: string }>;

  const ME = { user: {}, workspace: { id: "ws_1", slug: "acme", name: "Acme" }, scopes: ["strings:read"], apps: [] };
  const SUMMARY = { id: "app_web1", ...APP, name: "Web", keyCount: 3 };
  const item = (namespace: string, key: string, text: string) => ({
    id: `key_${key}`,
    appId: "app_web1",
    namespace,
    key,
    translations: text ? { en: { text, state: "approved" } } : {},
  });

  function server(answers: Record<string, unknown>) {
    globalThis.fetch = (async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = String(input);
      if (url.endsWith("/v1/me")) return new Response(JSON.stringify(ME));
      const name = url.split("/v1/ops/")[1]!;
      const body = JSON.parse(String(init?.body));
      if (name === "strings.apps.list") return new Response(JSON.stringify({ ok: true, data: { items: [SUMMARY] } }));
      if (name === "strings.keys.list") {
        pages.push({ cursor: body.input.cursor, locale: body.input.locale });
        return new Response(JSON.stringify({ ok: true, data: answers[body.input.cursor ?? "first"] }));
      }
      return new Response(JSON.stringify({ ok: false, error: { code: "NOT_FOUND", message: name } }), { status: 404 });
    }) as typeof fetch;
  }

  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), "lefine-types-cmd-"));
    process.env.LEFINE_HOME = join(dir, "home");
    process.env.LEFINE_TOKEN = "lfn_test_token_value";
    process.env.LEFINE_API_URL = "http://api.test";
    logs = [];
    pages = [];
    console.log = (...a: unknown[]) => void logs.push(a.join(" "));
    console.error = (...a: unknown[]) => void logs.push(a.join(" "));
    process.exit = ((code?: number) => {
      throw new Error(`exit:${code ?? 0}`);
    }) as typeof process.exit;
  });
  afterEach(() => {
    globalThis.fetch = realFetch;
    process.exit = realExit;
    console.log = realLog;
    console.error = realErr;
    delete process.env.LEFINE_HOME;
    delete process.env.LEFINE_TOKEN;
    delete process.env.LEFINE_API_URL;
    rmSync(dir, { recursive: true, force: true });
  });

  // DX walk 2026-10-29: Vite's tsconfig.app.json includes only src/, so a root lefine-strings.d.ts was never read.
  it("with src/lefine.ts (Vite, TanStack Start) the file goes to src/, beside it; with lefine.ts at the root, to the root", async () => {
    writeFileSync(join(dir, "package.json"), JSON.stringify({ dependencies: { lefine: "^0.1.0" } }));
    mkdirSync(join(dir, "src"));
    writeFileSync(join(dir, "src", "lefine.ts"), 'export const strings = createStrings({ project: "app_0123456789abcdef0123456789abcdef" });');
    expect(defaultTypesFile(dir)).toBe(join(dir, "src", "lefine-strings.d.ts"));
    server({ first: { items: [item("common", "hello", "Hello")], nextCursor: null } });
    await stringsTypesCommand({ project: "acme/web", dir, json: true });
    expect(existsSync(join(dir, "src", "lefine-strings.d.ts"))).toBe(true);
    expect(existsSync(join(dir, "lefine-strings.d.ts"))).toBe(false);
    writeFileSync(join(dir, "lefine.ts"), "");
    expect(defaultTypesFile(dir)).toBe(join(dir, "lefine-strings.d.ts"));
  });

  it("reads every page in the source language and writes lefine-strings.d.ts", async () => {
    writeFileSync(join(dir, "package.json"), JSON.stringify({ dependencies: { "next-intl": "^4" } }));
    server({
      first: { items: [item("common", "hello", "Hello {name}")], nextCursor: "c2" },
      c2: { items: [item("common", "bye", "Bye"), item("common", "new", "")], nextCursor: null },
    });
    await stringsTypesCommand({ project: "acme/web", dir, json: true });
    expect(pages).toEqual([{ cursor: undefined, locale: "en" }, { cursor: "c2", locale: "en" }]);
    const text = readFileSync(join(dir, "lefine-strings.d.ts"), "utf-8");
    expect(text).toContain('"hello": "Hello {name}";');
    expect(text).toContain('"new": string;');
    expect(text).toContain('declare module "next-intl"');
    expect(JSON.parse(logs.at(-1)!)).toMatchObject({ keys: 3, binding: "next-intl", conflicts: [] });
  });

  it("writes nothing when the list repeats a page", async () => {
    server({ first: { items: [item("common", "hello", "Hi")], nextCursor: "c2" }, c2: { items: [], nextCursor: "c2" } });
    await expect(stringsTypesCommand({ project: "acme/web", dir })).rejects.toThrow("exit:1");
    expect(logs.join("\n")).toContain("repeated a page");
    expect(() => readFileSync(join(dir, "lefine-strings.d.ts"))).toThrow();
  });

  it("refuses an output that is not a .d.ts and an unknown binding", async () => {
    server({ first: { items: [], nextCursor: null } });
    await expect(stringsTypesCommand({ project: "acme/web", dir, output: "keys.ts" })).rejects.toThrow("exit:1");
    expect(logs.join("\n")).toContain("must end in .d.ts");
    await expect(stringsTypesCommand({ project: "acme/web", dir, binding: "i18next" })).rejects.toThrow("exit:1");
    expect(logs.join("\n")).toContain("--binding must be one of next-intl, use-intl, lefine/strings, none");
  });
});
